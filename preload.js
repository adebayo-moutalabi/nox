const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('nox', {
  ask: (text) => ipcRenderer.invoke('nox:ask', text),
  speak: (text) => ipcRenderer.invoke('nox:speak', text),
  transcribe: (buf) => ipcRenderer.invoke('nox:transcribe', buf),
  getState: () => ipcRenderer.invoke('nox:getState'),
  setSettings: (s) => ipcRenderer.invoke('nox:setSettings', s),
  resetTask: () => ipcRenderer.invoke('nox:resetTask'),
  greet: () => ipcRenderer.invoke('nox:greet'),
  getCatalog: () => ipcRenderer.invoke('nox:getCatalog'),
  saveProfile: (p) => ipcRenderer.invoke('nox:saveProfile', p),
  onboardingDone: () => ipcRenderer.invoke('nox:onboardingDone'),
  resetOnboarding: () => ipcRenderer.invoke('nox:resetOnboarding'),
  forgetFact: (id) => ipcRenderer.invoke('nox:forgetFact', id),
  addNote: (text) => ipcRenderer.invoke('nox:addNote', text),
  removeNote: (id) => ipcRenderer.invoke('nox:removeNote', id),
  completeStep: () => ipcRenderer.invoke('nox:completeStep'),
  newTask: (text) => ipcRenderer.invoke('nox:newTask', text),
  startTimer: (min) => ipcRenderer.send('nox:startTimer', min),
  openDashboard: () => ipcRenderer.send('nox:openDashboard'),
  hide: () => ipcRenderer.send('nox:hide'),
  openApp: (id) => ipcRenderer.invoke('nox:openApp', id),
  onSuggestApp: (cb) => ipcRenderer.on('nox:suggestApp', (_e, a) => cb(a)),
  show: () => ipcRenderer.send('nox:show'),
  onState: (cb) => ipcRenderer.on('nox:state', (_e, d) => cb(d)),
  onStartTimer: (cb) => ipcRenderer.on('nox:startTimer', (_e, m) => cb(m)),
  onAskWatch: (cb) => ipcRenderer.on('nox:askWatch', () => cb()),
  // Connexions et mode jeu
  setApiKey: (k) => ipcRenderer.invoke('nox:setApiKey', k),
  setDemo: (on) => ipcRenderer.invoke('nox:setDemo', on),
  forgetApiKey: () => ipcRenderer.invoke('nox:forgetApiKey'),
  setCalendar: (url) => ipcRenderer.invoke('nox:setCalendar', url),
  setGmail: (user, pass) => ipcRenderer.invoke('nox:setGmail', user, pass),
  unwatch: (id) => ipcRenderer.invoke('nox:unwatch', id),
  readMail: (id) => ipcRenderer.invoke('nox:readMail', id),
  setTelegram: (token) => ipcRenderer.invoke('nox:setTelegram', token),
  telegramQr: () => ipcRenderer.invoke('nox:telegramQr'),
  timerDone: () => ipcRenderer.send('nox:timerDone'),
  timerState: (t) => ipcRenderer.send('nox:timerState', t),
  stopTimer: () => ipcRenderer.send('nox:stopTimer'),
  onStopTimer: (cb) => ipcRenderer.on('nox:stopTimer', () => cb()),
  onReward: (cb) => ipcRenderer.on('nox:reward', (_e, r) => cb(r)),
  onMail: (cb) => ipcRenderer.on('nox:mail', (_e, m) => cb(m)),
  realtimeToken: () => ipcRenderer.invoke('nox:realtimeToken'),
  realtimeInstructions: () => ipcRenderer.invoke('nox:realtimeInstructions'),
  tool: (name, args, userText) => ipcRenderer.invoke('nox:tool', name, args, userText),
  setRealtimeActive: (on) => ipcRenderer.send('nox:realtimeActive', on),
  remember: (role, text) => ipcRenderer.send('nox:remember', role, text),
  onEvent: (cb) => ipcRenderer.on('nox:event', (_e, d) => cb(d)),
  cursor: () => ipcRenderer.invoke('nox:cursor'),
  moveTo: (x, y) => ipcRenderer.send('nox:moveTo', x, y),
  quit: () => ipcRenderer.send('nox:quit'),
  onProactive: (cb) => ipcRenderer.on('nox:proactive', (_e, d) => cb(d)),
  onMood: (cb) => ipcRenderer.on('nox:mood', (_e, d) => cb(d)),
  onError: (cb) => ipcRenderer.on('nox:error', (_e, d) => cb(d))
});
